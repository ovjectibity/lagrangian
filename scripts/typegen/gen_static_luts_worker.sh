#!/usr/bin/env bash
# Export Postgres LUT rows as static worker Python dictionaries.
# Run init_db.sh first to create and seed the LUT tables.
# Uses the same POSTGRES_* settings as the DB scripts.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUTPUT="$REPO_ROOT/worker/worker-py/commondef/luts.py"

POSTGRES_HOST="${POSTGRES_HOST:-localhost}"
POSTGRES_PORT="${POSTGRES_PORT:-5432}"
POSTGRES_USER="${POSTGRES_USER:-lagrangian}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-lagrangian}"
POSTGRES_DB="${POSTGRES_DB:-lagrangian}"

for command in psql python3; do
  command -v "$command" >/dev/null 2>&1 || {
    echo "ERROR: $command not found in PATH" >&2
    exit 1
  }
done

snapshot="$(mktemp)"
trap 'rm -f "$snapshot"' EXIT

PGPASSWORD="$POSTGRES_PASSWORD" \
psql -X -q -A -t \
     -h "$POSTGRES_HOST" \
     -p "$POSTGRES_PORT" \
     -U "$POSTGRES_USER" \
     -d "$POSTGRES_DB" \
     --set=ON_ERROR_STOP=1 > "$snapshot" <<'SQL'
BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY;
SELECT jsonb_build_object(
    'workload_structure_lut', (
        SELECT COALESCE(
            jsonb_agg(to_jsonb(lut) ORDER BY workload_structure_id),
            '[]'::JSONB
        )
        FROM workloads.workload_structure_lut AS lut
    ),
    'user_metrics_lut', (
        SELECT COALESCE(
            jsonb_agg(to_jsonb(lut) ORDER BY metric_id),
            '[]'::JSONB
        )
        FROM workloads.user_metrics_lut AS lut
    )
);
COMMIT;
SQL

python3 - "$snapshot" "$OUTPUT" <<'PY'
import json
from pathlib import Path
from pprint import pformat
import stat
import sys
import tempfile

snapshot = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
output = Path(sys.argv[2])
structures = {
    row["workload_structure_id"]: row
    for row in snapshot["workload_structure_lut"]
}
metrics = {
    row["metric_id"]: row
    for row in snapshot["user_metrics_lut"]
}
code = (
    '"""Static workload LUT data exported from Postgres.\n\n'
    'Generated by scripts/typegen/gen_static_luts_worker.sh; do not edit.\n'
    '"""\n\n'
    "WORKLOAD_STRUCTURE_LUT = "
    + pformat(structures, sort_dicts=True, width=88)
    + "\n\nUSER_METRICS_LUT = "
    + pformat(metrics, sort_dicts=True, width=88)
    + "\n"
)
compile(code, str(output), "exec")

if not output.exists() or output.read_text(encoding="utf-8") != code:
    output.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(output.stat().st_mode) if output.exists() else 0o644
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=output.parent,
        prefix=".luts-", suffix=".tmp", delete=False,
    ) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(code)
        except BaseException:
            temporary.unlink()
            raise
    try:
        temporary.chmod(mode)
        temporary.replace(output)
    finally:
        temporary.unlink(missing_ok=True)

print(
    f"Generated: {output} "
    f"({len(structures)} structures, {len(metrics)} metrics)"
)
PY

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use typeshare::typeshare;
use utoipa::ToSchema;

use app_proc_macros::variant_source;

use crate::commondef::records::workload_graph::MLModel;

/// Model file format recorded for an asset.
#[derive(
    Debug,
    Clone,
    Serialize,
    Deserialize,
    PartialEq,
    Eq,
    sqlx::Type,
    ToSchema,
)]
#[serde(rename_all = "snake_case")]
#[sqlx(type_name = "text", rename_all = "snake_case")]
#[typeshare]
pub enum SimulationModelType {
    Mjcf,
    Urdf,
    Usd,
}

/// Model file format recorded for an asset.
#[derive(
    Debug,
    Clone,
    Serialize,
    Deserialize,
    PartialEq,
    Eq,
    sqlx::Type,
    ToSchema,
)]
#[serde(rename_all = "snake_case")]
#[sqlx(type_name = "text", rename_all = "snake_case")]
#[typeshare]
pub enum SimulationModelFileType {
    Zip
}

/// Reference to a stored simulation model.
#[variant_source]
#[derive(
    Debug, Clone, Serialize, Deserialize, ToSchema,
)]
#[typeshare]
pub struct SimulationModelRef {
    pub project_id: String,
    pub simulation_model_id: String,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
    pub name: String,
    pub uri_path: String,
    pub model_type: SimulationModelType,
    pub file_type: SimulationModelFileType,
    pub base_file_name: String
}

#[derive(
    Debug, Clone, Serialize, Deserialize, ToSchema,
    sqlx::Type,
)]
#[serde(rename_all = "snake_case")]
#[sqlx(type_name = "text", rename_all = "snake_case")]
#[typeshare]
pub enum CheckpointModelType {
    Policy,
    Value,
    FlowNoise
}

/// Reference to a stored checkpoint and its training state.
#[variant_source]
#[derive(
    Debug, Clone, Serialize, Deserialize, ToSchema,
)]
#[typeshare]
pub struct CheckpointRef {
    pub checkpoint_id: String,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
    pub name: String,
    pub uri_path: String,
    pub workload_id: Option<String>,
    /// Present for checkpoints generated by training workloads.
    pub workload_structure_id: Option<i32>,
    /// Coordinates in LUT order, excluding na_indices positions.
    pub workload_structure_state: Option<Vec<u32>>,
    /// Zero-based LUT positions omitted from coordinates.
    /// Empty when no dimensions are excluded.
    pub na_indices: Vec<u32>,
    pub model_type: CheckpointModelType,
    pub model_spec: MLModel
}

/// Reference to a camera frame captured at a workload state.
#[variant_source]
#[derive(
    Debug, Clone, Serialize, Deserialize, ToSchema,
)]
#[typeshare]
pub struct TrajectoryCameraFrameRef {
    pub camera_frame_id: String,
    pub workload_id: String,
    pub workload_structure_id: i32,
    /// Numeric coordinates in the structure LUT's declared order.
    pub workload_structure_state: Vec<u32>,
    pub camera_id: String,
    pub model_camera_name: String,
    pub uri_path: String,
    pub simulation_model_id: String,
}

//! Worker transport and app-owned asset storage.

pub mod common_worker_controller;
pub mod local_worker_controller;
pub mod remote_worker_controller;

use aws_sdk_s3::Client;
use aws_sdk_s3::primitives::ByteStream;
use uuid::Uuid;

use crate::db::validations;
use common_worker_controller::Result;

/// Stable final identifiers make failed ingestion safe to retry.
pub fn final_record_id(
    workload_id: &str,
    kind: &str,
    temporary_id: &str,
) -> String {
    Uuid::new_v5(
        &Uuid::NAMESPACE_URL,
        format!("lagrangian:{workload_id}:{kind}:{temporary_id}")
            .as_bytes(),
    )
    .to_string()
}

/// Persistent model keys are scoped to projects for both uploads
/// and models generated by a worker.
pub fn model_key(project_id: &str, id: &str) -> String {
    format!("app/projects/{project_id}/models/{id}/m_{id}.zip")
}

/// Copy an allocated worker object without exposing its location
/// to clients. The source is retained until ingestion succeeds.
pub async fn promote_asset(
    s3: &Client,
    bucket: &str,
    source_uri: &str,
    expected_key: &str,
    destination: &str,
) -> Result<String> {
    validations::validate_worker_asset_uri(
        source_uri,
        bucket,
        expected_key,
    )?;
    s3.copy_object()
        .bucket(bucket)
        .key(destination)
        .copy_source(format!("{bucket}/{expected_key}"))
        .send()
        .await?;
    Ok(format!("s3://{bucket}/{destination}"))
}

/// Upload a user-supplied model package with normal SDK retries.
pub async fn upload_model(
    s3: &Client,
    bucket: &str,
    project_id: &str,
    id: &str,
    contents: Vec<u8>,
) -> Result<String> {
    let key = model_key(project_id, id);
    s3.put_object()
        .bucket(bucket)
        .key(&key)
        .content_type("application/zip")
        .body(ByteStream::from(contents))
        .send()
        .await?;
    Ok(format!("s3://{bucket}/{key}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_ids_are_stable_and_scoped() {
        let id = final_record_id("w1", "models", "temp");
        assert_eq!(id, final_record_id("w1", "models", "temp"));
        assert_ne!(id, final_record_id("w2", "models", "temp"));
        assert_ne!(id, final_record_id("w1", "frames", "temp"));
        assert_eq!(
            model_key("p", "m"),
            "app/projects/p/models/m/m_m.zip"
        );
    }
}
